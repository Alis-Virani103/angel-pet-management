interface LanguageContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (text: string) => string;
  confirm: (text: string) => boolean;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = typeof localStorage !== 'undefined' ? localStorage.getItem(LANGUAGE_STORAGE_KEY) : null;
    return saved === 'gu' ? 'gu' : 'en';
  });

  const setLanguage = (nextLanguage: Language) => {
    setLanguageState(nextLanguage);
    localStorage.setItem(LANGUAGE_STORAGE_KEY, nextLanguage);
  };

  useEffect(() => {
    document.documentElement.lang = language === 'gu' ? 'gu' : 'en';
    if (language !== 'gu') return;

    const translateStaticDom = () => {
      const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
      const textNodes: Text[] = [];
      let node: Node | null;
      while ((node = walker.nextNode())) textNodes.push(node as Text);
      textNodes.forEach((textNode) => {
        const original = textNode.nodeValue?.trim();
        if (!original || !gujarati[original]) return;
        textNode.nodeValue = textNode.nodeValue?.replace(original, gujarati[original]) || gujarati[original];
      });
      document.querySelectorAll<HTMLElement>('[placeholder], [title], [aria-label]').forEach((element) => {
        ['placeholder', 'title', 'aria-label'].forEach((attribute) => {
          const value = element.getAttribute(attribute);
          if (value && gujarati[value]) element.setAttribute(attribute, gujarati[value]);
        });
      });
    };

    translateStaticDom();
    const observer = new MutationObserver(translateStaticDom);
    observer.observe(document.body, { childList: true, subtree: true });
    return () => observer.disconnect();
  }, [language]);

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage,
    t: (text: string) => language === 'gu' ? gujarati[text] || text : text,
    confirm: (text: string) => window.confirm(language === 'gu' ? gujarati[text] || text : text)
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
};

export const useTranslation = (): LanguageContextValue => {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useTranslation must be used inside LanguageProvider');
  return context;
};
